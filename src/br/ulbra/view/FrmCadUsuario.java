    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed

        String senha = txtSenha.getText();
        String confirmar = txtConfirmarSenha.getText();
        
        String cpf = txtCpf.getText().trim().replaceAll("\\D", "");
        if (!cpf.matches("\\d{11}")) {
        JOptionPane.showMessageDialog(this, "CPF inválido! Digite apenas 11 números.");
        return;
    }
        Usuario u = new Usuario();
        if (!u.validarSenha(senha)) {
            JOptionPane.showMessageDialog(this, "A senha deve conter pelo menos 8 caracteres, incluindo letras maiúsculas, minúsculas, números e símbolos.");
            return;
        }

        if (!senha.equals(confirmar)) {
            JOptionPane.showMessageDialog(this, "As senhas não coincidem.");
            return;
        }

        u.setSenha(senha);

        u.setNome(txtNome.getText());
        u.setEmail(txtEmail.getText());
        u.setSenha(senha);
        u.setTelefone(txtFone.getText());
        u.setCpf(txtCpf.getText());
        u.setCepusu(txtCep.getText());
        u.setLogradourousu(txtLogradouro.getText());
        u.setNumerousu(txtNumero.getText());
        u.setBairrousu(txtBairro.getText());
        u.setCidadeusu(txtCidade.getText());
        u.setEstado(txtEstado.getText());

        try {
            UsuarioDAO dao = new UsuarioDAO();
            dao.salvar(u);
            JOptionPane.showMessageDialog(this, "Usuário cadastrado com sucesso!");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao salvar o usuário: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

