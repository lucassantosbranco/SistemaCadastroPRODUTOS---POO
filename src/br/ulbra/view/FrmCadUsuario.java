    private void buscarEndereco() {
        String cep = txtCep.getText().trim().replace("-", "");

        if (cep.length() == 8) {
            endereco end = ViaCepService.buscarEnderecoPorCep(cep);
            if (end.getCep() != null) {
                txtLogradouro.setText(end.getLogradouro());
                txtBairro.setText(end.getBairro());
                txtCidade.setText(end.getLocalidade());
                txtEstado.setText(end.getUf());
            } else {
                JOptionPane.showMessageDialog(this, "CEP não encontrado.");
            }
        } else {
            JOptionPane.showMessageDialog(this, "CEP inválido. Digite 8 dígitos.");
        }

    }

    private boolean validarSenhaCampos() {
        String senha = txtSenha.getText();
        String confirmarSenha = txtConfirmarSenha.getText();
        Usuario u = new Usuario();

        if (!u.validarSenha(senha)) {
            JOptionPane.showMessageDialog(this, "A senha deve conter pelo menos 8 caracteres, incluindo letra maiúscula, minúscula, número e caractere especial.");
            return false;
        }

        if (!u.confirmarSenha(senha, confirmarSenha)) {
            JOptionPane.showMessageDialog(this, "As senhas não coincidem.");
            return false;
        }
        u.setNome(txtNome.getText());
        u.setEmail(txtEmail.getText());
        u.setSenha(senha);
        u.setTelefone(txtFone.getText());
        u.setCpf(txtCpf.getText());
        u.setCepusu(txtCep.getText());
        u.setLogradourousu(txtLogradouro.getText());
        u.setNumerousu(txtNumero.getText());
        u.setBairrousu(txtBairro.getText());
        u.setCidadeusu(txtCidade.getText());
        u.setEstado(txtEstado.getText());

        return true;
    }

