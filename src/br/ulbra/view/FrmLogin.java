    private void realizarLogin() {
        String email = txtEmail.getText();  
        String senha = new String( jPasswordField1.getPassword());
        
        UsuarioDAO usuarioDAO;
       try {
            usuarioDAO = new UsuarioDAO();
            boolean loginValido = usuarioDAO.checkLogin(email, senha);

            if (loginValido) {
                JOptionPane.showMessageDialog(this, "Login bem-sucedido!");
                new FrmDashBoard().setVisible(true);
                this.dispose(); // Fecha a tela de login
            } else {
                JOptionPane.showMessageDialog(this, "Usuário ou senha inválidos.");
                abrirTelaCadastro(); // Corrigido para chamar o método correto
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao realizar login: " + e.getMessage());
        }
    }
     private void abrirTelaCadastro() {
        new FrmCadUsuario().setVisible(true);  
        this.dispose();  
    }
